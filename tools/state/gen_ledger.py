#!/usr/bin/env python3
"""Сборка реестра аксиом `output/generated/Axioms.lean`.

В реестр попадает каждая запись `claims/C*.md` с фасетом `final: true` или со
статусом `proved-*`; имя объявления берётся из фасета `lean_theorem`, а не из
имени файла: перенос модуля между слоями имени не меняет.

Файл читает `tools/check/check.ps1`: он запускает `lake env lean` на нём и
сверяет множество аксиом с допустимым (`propext`, `Classical.choice`,
`Quot.sound`). Запись без `lean_theorem` пропускается и отмечается в файле
комментарием — молча терять её нельзя.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import facets as F  # noqa: E402

REL = "output/generated/Axioms.lean"
BANNER = "generated by tools/state/gen_ledger.py; do not edit"


def selected(data_units: list[F.Unit]) -> tuple[list[F.Unit], list[F.Unit]]:
    """`(записи с именем теоремы, записи без имени)`."""
    chosen: list[F.Unit] = []
    nameless: list[F.Unit] = []
    for unit in data_units:
        if unit.cls != "record":
            continue
        status = unit.status()
        if not (unit.is_true("final") or status.startswith("proved-")):
            continue
        if isinstance(unit.facets.get("lean_theorem"), str) and unit.facets["lean_theorem"].strip():
            chosen.append(unit)
        else:
            nameless.append(unit)
    return chosen, nameless


def render(units: list[F.Unit]) -> str:
    chosen, nameless = selected(units)
    lines = [
        "/-",
        "  " + BANNER,
        "",
        "  Реестр аксиом итоговых теорем: записи claims/C*.md с фасетом final: true",
        "  или статусом proved-*. Имена объявлений взяты из фасета lean_theorem.",
        "  Проверка: tools/check/check.ps1 запускает `lake env lean` на этом файле и",
        "  сверяет множество аксиом с допустимым (propext, Classical.choice, Quot.sound).",
        "-/",
        "import Involution",
        "",
    ]
    for unit in nameless:
        lines.append(
            f"-- ВНИМАНИЕ: {unit.id} ({unit.status() or 'без статуса'}) без фасета lean_theorem — в реестр не попала."
        )
    if nameless:
        lines.append("")
    if not chosen:
        lines.append("-- Записей с final: true или статусом proved-* пока нет.")
        lines.append("")
    for unit in chosen:
        lines.append(f"#print axioms {unit.facets['lean_theorem'].strip()}")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass
    parser = argparse.ArgumentParser(description="Сборка output/generated/Axioms.lean.")
    parser.add_argument("--root", default=str(Path(__file__).resolve().parents[2]), help="корень проекта")
    args = parser.parse_args(argv)

    root = Path(args.root).resolve()
    units, naming = F.load_units(root)
    chosen, nameless = selected(units)
    path = root / REL
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(units), encoding="utf-8", newline="\n")
    print(f"записан: {REL}; объявлений: {len(chosen)}; без lean_theorem: {len(nameless)}")
    for unit in nameless:
        print(f"  нет lean_theorem: {unit.rel} ({unit.id}, {unit.status() or 'без статуса'})")
    for note in naming:
        print(f"  замечание: {note}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
