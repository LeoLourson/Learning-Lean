def render_blueprint(data: dict) -> str:
    units = data["units"]
    edges = data["edges"]
    lines = [BANNER, "", "# План формализации", ""]

    statements = [u for u in units if u.cls == "statement"]
    if statements:
        unit = statements[0]
        lines.append(f"Постановка: {unit.id} — {markdown_cell(unit.facets.get('title'))} (`{unit.rel}`).")
    else:
        lines.append("Постановка не найдена: ожидается `claims/question.md`.")
    lines.append("")

    # --- узлы
    lines += ["## Узлы и зависимости", ""]
    node_units = [u for u in units if u.cls in ("record", "idea", "card")]
    if not node_units:
        lines.append("Узлов нет: `claims/` пуст или ещё наполняется.")
        lines.append("")
    else:
        edge_count = sum(len(v) for v in edges.values())
        cycles = data["cycles"]
        lines.append(
            f"Узлов: {len(node_units)}, связей `depends_on`: {edge_count}. "
            + ("Граф ацикличен." if not cycles else f"Найдены циклы: {len(cycles)}.")
        )
        lines.append("")
        lines += ["| id | title | status | depends_on | класс |", "| --- | --- | --- | --- | --- |"]
        for unit in node_units:
            lines.append(
                "| {id} | {title} | {status} | {deps} | {cls} |".format(
                    id=markdown_cell(unit.id),
                    title=markdown_cell(unit.facets.get("title")),
                    status=markdown_cell(unit.facets.get("status")),
                    deps=markdown_cell(unit.facets.get("depends_on")),
                    cls=unit.cls,
                )
            )
        lines.append("")

        mermaid_edges = [
            (node, dep)
            for node in sorted(edges)
            for dep in edges[node]
            if ID_OK_RE.match(node) and ID_OK_RE.match(dep)
        ]
        if mermaid_edges and not cycles:
            lines += ["```mermaid", "graph LR"]
            lines += [f"  {dep}[{dep}] --> {node}[{node}]" for node, dep in mermaid_edges]
            lines += ["```", ""]

    # --- слои
    lines += ["## Слои библиотеки", ""]
    if not data["layers"]:
        lines.append("Порядок слоёв не прочитан из `LAYOUT.md`.")
        lines.append("")
    else:
        lines += ["| Слой | Модули |", "| --- | --- |"]
        for name in data["layers"]:
            files = data["layer_modules"].get(name, [])
            cell = ", ".join(f"`{f}`" for f in files) if files else EMPTY
            lines.append(f"| {name} | {cell} |")
        lines.append("")
    elsewhere = data["elsewhere"]
    if elsewhere:
        lines.append(
            f"Вне слоёв: {len(elsewhere)} модулей прямо в `Involution/*.lean` (раскладка агента слоёв ещё не применена): "
            + ", ".join(f"`{f}`" for f in elsewhere)
            + "."
        )
    else:
        lines.append("Все модули лежат в каталогах слоёв.")
    lines.append("")

    # --- задачи
    lines += ["## Задачи внешнему исполнителю", ""]
    tasks = data["tasks"]
    if not tasks:
        lines.append("Задач нет: `tasks/A*/request.md` не найден.")
    else:
        lines += ["| id | title | status | goal | date |", "| --- | --- | --- | --- | --- |"]
        for unit in tasks:
            lines.append(
                "| {id} | {title} | {status} | {goal} | {date} |".format(
                    id=markdown_cell(unit.id),
                    title=markdown_cell(unit.facets.get("title")),
                    status=markdown_cell(unit.facets.get("status")),
                    goal=markdown_cell(unit.facets.get("goal")),
                    date=markdown_cell(unit.facets.get("date")),
                )
            )
    lines.append("")

    # --- источники
    lines += ["## Опись источников", ""]
    stats = data["stats"]
    if not data["registry_rel"]:
        lines.append("Реестр источников не найден: ожидается `sources/registry.json`.")
    else:
        lines.append(f"Опись: `{data['registry_rel']}`.")
        lines.append("")
        lines.append(f"* Кодов: {len(stats['codes'])} (уникальных: {len(stats['unique'])}).")
        lines.append(f"* С полным текстом локально (`output/literature/`): {len(stats['full'])}.")
        lines.append(f"* Полного текста нет: {len(stats['no_text'])}" + (f" — {', '.join(stats['no_text'])}." if stats["no_text"] else "."))
        if stats["missing_files"]:
            listed = "; ".join(f"{code}: {', '.join(files)}" for code, files in stats["missing_files"])
            lines.append(f"* Указан файл, которого нет: {listed}. Восстанавливает `tools/sources/lit.py fetch`.")
        if stats["no_code"]:
            lines.append(f"* Записей без кода: {len(stats['no_code'])}.")
        if data["registry_note"]:
            lines.append(f"* Замечание: {data['registry_note']}.")
    lines.append("")

    # --- замечания
    lines += ["## Замечания", ""]
    problems: list[str] = []
    if data["cycles"]:
        problems += ["циклы `depends_on`: " + "; ".join(" -> ".join(c) for c in data["cycles"])]
    if data["unresolved"]:
        problems.append("неразрешённые ссылки `depends_on`: " + ", ".join(sorted(set(data["unresolved"]))))
    if data["duplicates"]:
        problems.append("повторённые идентификаторы: " + "; ".join(data["duplicates"]))
    if data["naming"]:
        problems += list(data["naming"])
    if data["header_errors"]:
        problems += list(data["header_errors"])
    if data["layout_errors"]:
        problems += list(data["layout_errors"])
    if problems:
        lines += [f"* {p}" for p in problems]
    else:
        lines.append("Замечаний нет.")
    lines.append("")
    return "\n".join(lines).rstrip() + "\n"


# --------------------------------------------------------------------------
# запись и проверка
# --------------------------------------------------------------------------

TARGETS = (("index.md", render_index), ("blueprint.md", render_blueprint))


def main(argv: list[str] | None = None) -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass
    parser = argparse.ArgumentParser(description="Сборка index.md и blueprint.md из шапок единиц.")
    parser.add_argument("--root", default=str(Path(__file__).resolve().parents[2]), help="корень проекта")
    parser.add_argument("--check", action="store_true", help="не писать, только сообщить об устаревших файлах")
    args = parser.parse_args(argv)

    root = Path(args.root).resolve()
    data = collect(root)

    stale = 0
    for rel, render in TARGETS:
        path = root / rel
        fresh = render(data)
        try:
            current = path.read_text(encoding="utf-8") if path.is_file() else None
        except (OSError, UnicodeDecodeError) as exc:
            print(f"устарел: {rel} — не прочитан ({exc})", file=sys.stderr)
            stale += 1
            continue
        if current == fresh:
            if not args.check:
                print(f"без изменений: {rel}")
            continue
        if args.check:
            stale += 1
            print(f"устарел: {rel}" + ("" if current is not None else " (файла нет)"))
            if current is not None:
                diff = difflib.unified_diff(
                    current.split("\n"), fresh.split("\n"), fromfile=rel, tofile=rel + " (заново)", lineterm=""
                )
                for i, line in enumerate(diff):
                    if i >= 20:
                        print("  ...")
                        break
                    print("  " + line)
        else:
            path.write_text(fresh, encoding="utf-8", newline="\n")
            print(f"записан: {rel}")

    if args.check and stale:
        print(f"устаревших файлов: {stale}; запусти `python tools/state/build_index.py`.")
        return 1
    if args.check:
        print("index.md и blueprint.md свежие.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
