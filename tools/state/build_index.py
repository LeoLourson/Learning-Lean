def render_index(data: dict) -> str:
    units = data["units"]
    counts = {cls: sum(1 for u in units if u.cls == cls) for cls in ("record", "idea", "card", "statement", "task", "experiment")}
    lines = [BANNER, "", "# Сводка утверждений", ""]
    lines.append(
        "Единиц: {total}. Записей C: {record}, идей I: {idea}, карточек S: {card}, "
        "постановок: {statement}, задач A: {task}, опытов E: {experiment}.".format(
            total=len(units), **counts
        )
    )
    lines.append("")
    if not units:
        lines.append("Единиц нет: каталог `claims/` пуст или ещё наполняется.")
        lines.append("")
        return "\n".join(lines).rstrip() + "\n"

    lines += [
        "| id | title | status | depends_on | lean_theorem | checked_by |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for unit in units:
        lines.append(
            "| {id} | {title} | {status} | {deps} | {lean} | {checked} |".format(
                id=markdown_cell(unit.id),
                title=markdown_cell(unit.facets.get("title")),
                status=markdown_cell(unit.facets.get("status")),
                deps=markdown_cell(unit.facets.get("depends_on")),
                lean=code_cell(unit.facets.get("lean_theorem")),
                checked=markdown_cell(unit.facets.get("checked_by")),
            )
        )
    lines.append("")

    final = [u for u in units if u.is_true("final")]
    lines += ["## Итоговые теоремы (`final: true`)", ""]
    if final:
        for unit in final:
            lean = unit.facets.get("lean_theorem")
            lines.append(
                f"* {unit.id} — {markdown_cell(unit.facets.get('title'))}"
                + (f", `{lean}`" if lean else ", `lean_theorem` не указан")
            )
    else:
        lines.append("Нет записей с `final: true`.")
    lines.append("")

    ideas = [u for u in units if u.cls == "idea"]
    if ideas:
        lines += ["## Идеи", "", "| id | title | status | next |", "| --- | --- | --- | --- |"]
        for unit in ideas:
            lines.append(
                "| {id} | {title} | {status} | {next} |".format(
                    id=markdown_cell(unit.id),
                    title=markdown_cell(unit.facets.get("title")),
                    status=markdown_cell(unit.facets.get("status")),
                    next=markdown_cell(unit.facets.get("next")),
                )
            )
        lines.append("")

    cards = [u for u in units if u.cls == "card"]
    if cards:
        lines += ["## Карточки источников", "", "| id | title | status | source | applies_to | checked_by |", "| --- | --- | --- | --- | --- | --- |"]
        for unit in cards:
            lines.append(
                "| {id} | {title} | {status} | {source} | {applies} | {checked} |".format(
                    id=markdown_cell(unit.id),
                    title=markdown_cell(unit.facets.get("title")),
                    status=markdown_cell(unit.facets.get("status")),
                    source=markdown_cell(unit.facets.get("source")),
                    applies=markdown_cell(unit.facets.get("applies_to")),
                    checked=markdown_cell(unit.facets.get("checked_by")),
                )
            )
        lines.append("")

    tasks = data["tasks"]
    if tasks:
        lines += ["## Задачи внешнему исполнителю", "", "| id | title | status | goal |", "| --- | --- | --- | --- |"]
        for unit in tasks:
            lines.append(
                "| {id} | {title} | {status} | {goal} |".format(
                    id=markdown_cell(unit.id),
                    title=markdown_cell(unit.facets.get("title")),
                    status=markdown_cell(unit.facets.get("status")),
                    goal=markdown_cell(unit.facets.get("goal")),
                )
            )
        lines.append("")

    notes = list(data["naming"]) + list(data["header_errors"]) + list(data["duplicates"])
    if notes:
        lines += ["## Замечания к шапкам", ""]
        lines += [f"* {note}" for note in notes]
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


