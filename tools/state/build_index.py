#!/usr/bin/env python3
"""Сборка производных `index.md` и `blueprint.md` из шапок единиц.

Читает `claims/*.md` (записи C, идеи I, карточки S, постановка claims/question.md),
`tasks/A*/request.md`, `experiments/E*/README.md`, каталоги слоёв
`Involution/<Слой>/*.lean` и опись `sources/registry.json`.

Собирает:
* `index.md` — сводку утверждений (id, title, status, depends_on,
  lean_theorem, checked_by; числовая сортировка);
* `blueprint.md` — узлы и зависимости (с проверкой ацикличности), слои
  библиотеки, задачи, опись источников.

Режим `--check` ничего не пишет: печатает расхождения и возвращает 1, если
файлы устарели. Ни один производный файл не содержит даты: иначе проверка
свежести была бы невозможна.
"""

from __future__ import annotations

import argparse
import difflib
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import facets as F  # noqa: E402

BANNER = "<!-- generated by tools/state/build_index.py; do not edit -->"
EMPTY = "—"
ID_OK_RE = re.compile(r"^[A-Za-z]+\d+$")


# --------------------------------------------------------------------------
# сбор данных
# --------------------------------------------------------------------------


def markdown_cell(value, fallback: str = EMPTY) -> str:
    """Значение фасета в ячейке markdown-таблицы."""
    if value is None or value == "":
        return fallback
    if isinstance(value, bool):
        text = "true" if value else "false"
    elif isinstance(value, (list, tuple)):
        text = ", ".join(str(v) for v in value) if value else fallback
    else:
        text = str(value)
    text = text.replace("|", r"\lvert").replace("\n", " ").strip()
    return text or fallback


def code_cell(value) -> str:
    text = markdown_cell(value)
    return text if text == EMPTY else f"`{text}`"


def find_cycles(edges: dict[str, list[str]]) -> list[list[str]]:
    """Циклы в ориентированном графе `узел -> зависимости`."""
    cycles: list[list[str]] = []
    seen: set[str] = set()
    colour: dict[str, int] = {}

    def visit(node: str, path: list[str]) -> None:
        colour[node] = 1
        for dep in edges.get(node, []):
            if colour.get(dep) == 1:
                cycle = path[path.index(dep):] + [dep] if dep in path else [node, dep]
                key = "->".join(sorted(set(cycle)))
                if key not in seen:
                    seen.add(key)
                    cycles.append(cycle)
            elif colour.get(dep, 0) == 0:
                visit(dep, path + [dep])
        colour[node] = 2

    for node in sorted(edges):
        if colour.get(node, 0) == 0:
            visit(node, [node])
    return cycles


def collect(root: Path) -> dict:
    units, naming = F.load_units(root)
    units = sorted(units, key=lambda u: F.id_sort_key(u.id))

    by_id: dict[str, F.Unit] = {}
    duplicates: list[str] = []
    for unit in units:
        if unit.id in by_id:
            duplicates.append(f"{unit.id}: {by_id[unit.id].rel} и {unit.rel}")
        else:
            by_id[unit.id] = unit

    edges: dict[str, list[str]] = {}
    unresolved: list[str] = []
    for unit in units:
        deps = unit.facets.get("depends_on")
        deps = deps if isinstance(deps, list) else []
        edges[unit.id] = [str(d) for d in deps]
        for dep in edges[unit.id]:
            if dep not in by_id:
                unresolved.append(f"{unit.id} -> {dep}")

    rules, layout_errors = F.classes_from_layout(root)
    layers = F.layer_order(root)
    modules = F.lean_modules(root)
    layer_modules: dict[str, list[str]] = {name: [] for name in layers}
    elsewhere: list[str] = []
    for rel in modules.values():
        parts = rel.split("/")
        if len(parts) == 3 and parts[1] in layer_modules:
            layer_modules[parts[1]].append(Path(parts[2]).name)
        else:
            elsewhere.append(Path(rel).name)
    for name in layer_modules:
        layer_modules[name].sort()

    tasks = [u for u in units if u.cls == "task"]
    entries, registry_rel, registry_note = F.load_registry(root)
    stats = F.registry_stats(root, entries)

    header_errors = [e for unit in units for e in unit.header_errors]
    return {
        "units": units,
        "by_id": by_id,
        "naming": naming,
        "duplicates": duplicates,
        "edges": edges,
        "unresolved": unresolved,
        "cycles": find_cycles(edges),
        "layout_errors": layout_errors,
        "layers": layers,
        "layer_modules": layer_modules,
        "elsewhere": elsewhere,
        "tasks": tasks,
        "registry_rel": registry_rel,
        "registry_note": registry_note,
        "stats": stats,
        "header_errors": header_errors,
    }


