IMPORT_RE = re.compile(r"^\s*(?:public\s+)?import\s+(.+?)\s*$", re.M)


def lean_modules(root: Path) -> dict[str, str]:
    """`{имя модуля: путь относительно корня}` для файлов Involution/**/*.lean."""
    modules: dict[str, str] = {}
    base = root / "Involution"
    if not base.is_dir():
        return modules
    for path in sorted(base.rglob("*.lean")):
        rel = path.relative_to(root).as_posix()
        modules[module_of(rel)] = rel
    return modules


def module_of(rel: str) -> str:
    """Путь файла -> имя модуля Lean."""
    stem = rel[:-len(".lean")] if rel.endswith(".lean") else rel
    return stem.replace("/", ".")


def parse_imports(text: str) -> list[str]:
    modules: list[str] = []
    for match in IMPORT_RE.finditer(text):
        modules.extend(match.group(1).split())
    return modules


def module_header(text: str) -> str:
    """Первая непустая строка файла: у модуля нового образца это `module`."""
    for raw in text.replace("\r\n", "\n").split("\n"):
        line = raw.strip().lstrip("\ufeff")
        if line:
            return line
    return ""


def lean_layer(module: str, layers: list[str]) -> int | None:
    """Индекс слоя модуля или None, если модуль вне слоёв."""
    parts = module.split(".")
    if len(parts) >= 2 and parts[1] in layers:
        return layers.index(parts[1])
    return None
