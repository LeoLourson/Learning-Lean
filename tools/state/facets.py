def _strip_comment(value: str) -> str:
    """Убирает комментарий `#` вне кавычек и вне списка."""
    out, quote, depth = [], None, 0
    for i, ch in enumerate(value):
        if quote:
            out.append(ch)
            if ch == quote:
                quote = None
            continue
        if ch in "'\"":
            quote = ch
            out.append(ch)
            continue
        if ch == "[":
            depth += 1
        elif ch == "]":
            depth -= 1
        elif ch == "#" and depth == 0 and (i == 0 or value[i - 1] in " \t"):
            break
        out.append(ch)
    return "".join(out).strip()


def _parse_scalar(text):
    t = text.strip()
    if len(t) >= 2 and t[0] == t[-1] and t[0] in "'\"":
        return t[1:-1]
    low = t.lower()
    if low in ("true", "false"):
        return low == "true"
    if low in ("null", "~", ""):
        return None
    return t


def _split_items(inner: str) -> list[str]:
    items, cur, quote = [], [], None
    for ch in inner:
        if quote:
            cur.append(ch)
            if ch == quote:
                quote = None
        elif ch in "'\"":
            quote = ch
            cur.append(ch)
        elif ch == ",":
            items.append("".join(cur))
            cur = []
        else:
            cur.append(ch)
    items.append("".join(cur))
    return items


def _parse_list(text: str) -> list:
    inner = text.strip()[1:-1]
    out = []
    for item in _split_items(inner):
        value = _parse_scalar(item)
        if value is not None and value != "":
            out.append(value)
    return out


def split_front_matter(text: str):
    """Возвращает `(facets | None, ошибки, тело)` для плоской шапки."""
    errors: list[str] = []
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    if text.startswith("\ufeff"):
        text = text[1:]
    lines = text.split("\n")
    if not lines or not _FRONT_RE.match(lines[0]):
        return None, ["нет шапки: файл не начинается строкой ---"], text
    end = None
    for i in range(1, len(lines)):
        if _FRONT_RE.match(lines[i]):
            end = i
            break
    if end is None:
        return None, ["шапка не закрыта строкой ---"], text
    facets: dict = {}
    for lineno, raw in enumerate(lines[1:end], start=2):
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        if raw[0] in " \t":
            errors.append(f"строка {lineno}: вложенность запрещена, шапка плоская")
            continue
        m = _KEY_RE.match(raw)
        if not m:
            errors.append(f"строка {lineno}: не разобрана как «ключ: значение»")
            continue
        key, value = m.group(1), _strip_comment(m.group(2))
        if key in facets:
            errors.append(f"строка {lineno}: ключ {key} повторён")
        if value == "":
            facets[key] = None
            errors.append(f"строка {lineno}: {key} без значения")
            continue
        if value.startswith("["):
            if not value.endswith("]"):
                errors.append(f"строка {lineno}: список не закрыт ]")
                facets[key] = []
                continue
            facets[key] = _parse_list(value)
        elif value.startswith("{"):
            errors.append(f"строка {lineno}: вложенный словарь запрещён")
            facets[key] = None
        else:
            facets[key] = _parse_scalar(value)
    return facets, errors, "\n".join(lines[end + 1:])


