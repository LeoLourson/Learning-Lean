REGISTRY_CANDIDATES = ("sources/registry.json", "sources/registry.json")
TEXT_FIELDS = ("tex", "filename")


def load_registry(root: Path):
    """Возвращает `(entries, rel | '', замечание)`.

    Основной путь — `sources/registry.json`; пока агент вершины `sources` его не
    переименовал, читается старый `sources/registry.json`.
    """
    for rel in REGISTRY_CANDIDATES:
        path = root / rel
        if not path.is_file():
            continue
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
            return [], rel, f"реестр не разобран: {exc}"
        if isinstance(data, dict):
            for key in ("papers", "sources", "items", "entries"):
                if isinstance(data.get(key), list):
                    data = data[key]
                    break
        if not isinstance(data, list):
            return [], rel, "ожидался список записей"
        note = "" if rel.endswith("registry.json") else "реестр ещё не переименован в sources/registry.json"
        return data, rel, note
    return [], "", "файла реестра нет: ожидается sources/registry.json"


def registry_stats(root: Path, entries: list):
    """Сколько кодов и у скольких есть полный текст локально."""
    lit = root / "output" / "literature"
    codes, full, no_text, missing_files, no_code = [], [], [], [], []
    for entry in entries:
        if not isinstance(entry, dict):
            continue
        code = entry.get("code")
        code = str(code).strip() if code else ""
        if not code:
            no_code.append(str(entry)[:60])
            continue
        codes.append(code)
        fields = [f for f in TEXT_FIELDS if entry.get(f)]
        present = [f for f in fields if (lit / str(entry[f])).is_file()]
        if present:
            full.append(code)
        elif fields:
            missing_files.append((code, [str(entry[f]) for f in fields]))
        else:
            no_text.append(code)
    return {
        "codes": codes,
        "full": full,
        "no_text": no_text,
        "missing_files": missing_files,
        "no_code": no_code,
        "unique": sorted(set(codes), key=id_sort_key),
    }


