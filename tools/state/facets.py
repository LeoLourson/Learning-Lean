@dataclass
class ClassRule:
    name: str
    patterns: list[str]
    author: str
    derived: bool


def _backticked(cell: str) -> list[str]:
    return re.findall(r"`([^`]+)`", cell)


def classes_from_layout(root: Path):
    """Читает обе таблицы LAYOUT.md: `(rules, errors)`.

    Строка класса начинается с обратной кавычки во втором столбце таблицы.
    """
    path = root / "LAYOUT.md"
    rules: list[ClassRule] = []
    if not path.is_file():
        return rules, ["LAYOUT.md не найден"]
    lines = path.read_text(encoding="utf-8").replace("\r\n", "\n").split("\n")
    section = ""
    for raw in lines:
        line = raw.strip()
        if line.startswith("## "):
            # Таблицы классов — только «Первичное» и «Производное»;
            # «Куда переносится старое дерево» имеет такой же вид строк, но это
            # не классы, а маршрут разовой реорганизации.
            title = line[3:].strip()
            if title.startswith("Первичное"):
                section = "primary"
            elif title.startswith("Производное"):
                section = "derived"
            else:
                section = ""
            continue
        if not section or not line.startswith("| `"):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) < 3:
            continue
        name_cell = _backticked(cells[0])
        if not name_cell:
            continue
        patterns = _backticked(cells[1])
        if not patterns:
            continue
        rules.append(
            ClassRule(
                name=name_cell[0],
                patterns=patterns,
                author=cells[2],
                derived=(section == "derived"),
            )
        )
    return rules, []


def layer_order(root: Path) -> list[str]:
    """Порядок слоёв библиотеки из строки «Слои библиотеки:» LAYOUT.md."""
    path = root / "LAYOUT.md"
    if not path.is_file():
        return []
    text = path.read_text(encoding="utf-8")
    m = re.search(r"Слои библиотеки:", text)
    if not m:
        return []
    paragraph = text[m.end():].split("\n\n")[0]
    return _backticked(paragraph)


def pattern_to_regex(pattern: str) -> re.Pattern:
    """Маска LAYOUT.md (`**`, `*`, `<Слой>`) -> регулярное выражение пути."""
    pattern = re.sub(r"<[^>]+>", "*", pattern)
    out = []
    i = 0
    while i < len(pattern):
        ch = pattern[i]
        if ch == "*":
            if pattern[i:i + 2] == "**":
                out.append(".*")
                i += 2
                continue
            out.append("[^/]*")
        elif ch == "?":
            out.append("[^/]")
        else:
            out.append(re.escape(ch))
        i += 1
    return re.compile("^" + "".join(out) + "$")


def classify(rel: str, rules: list[ClassRule]) -> list[ClassRule]:
    """Все классы, чья маска накрывает путь. Норма — ровно один."""
    return [rule for rule in rules if any(pattern_to_regex(p).match(rel) for p in rule.patterns)]


def tracked_files(root: Path) -> list[str]:
    """Все файлы новой папки, кроме .git, .lake, output, .dsh, __pycache__."""
    found: list[str] = []
    for path in sorted(root.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(root).as_posix()
        parts = rel.split("/")
        if any(part in DIRS_EXCLUDED for part in parts):
            continue
        found.append(rel)
    return found


