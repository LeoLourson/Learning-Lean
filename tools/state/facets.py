@dataclass
class Unit:
    cls: str
    rel: str
    path: Path
    facets: dict = field(default_factory=dict)
    header_errors: list[str] = field(default_factory=list)
    read_error: str = ""
    id_hint: str = ""

    @property
    def id(self) -> str:
        value = self.facets.get("id")
        if isinstance(value, str) and value:
            return value
        return self.id_hint

    def get(self, key: str, default=None):
        value = self.facets.get(key, default)
        return default if value is None else value

    def is_true(self, key: str) -> bool:
        return self.facets.get(key) is True

    def status(self) -> str:
        value = self.facets.get("status")
        return value if isinstance(value, str) else ""


def _unit(cls: str, rel: str, path: Path, id_hint: str) -> Unit:
    unit = Unit(cls=cls, rel=rel, path=path, id_hint=id_hint)
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        unit.read_error = f"не прочитан: {exc}"
        return unit
    except UnicodeDecodeError as exc:
        unit.read_error = f"не UTF-8: {exc}"
        return unit
    facets, errors, _body = split_front_matter(text)
    unit.header_errors = list(errors)
    unit.facets = facets or {}
    if facets is None:
        unit.facets = {}
    return unit


def load_units(root: Path):
    """Читает единицы всех классов.

    Возвращает `(units, naming_errors)`. Отсутствие каталогов — не ошибка:
    перечень единиц тогда пуст.
    """
    units: list[Unit] = []
    naming: list[str] = []

    claims = root / "claims"
    if claims.is_dir():
        for path in sorted(claims.iterdir(), key=lambda p: p.name):
            if not path.is_file() or path.suffix != ".md":
                continue
            rel = path.relative_to(root).as_posix()
            if path.name == "question.md":
                units.append(_unit("statement", rel, path, "Q"))
                continue
            m = CLAIM_FILE_RE.match(path.name)
            if not m:
                naming.append(f"{rel}: имя не вида <id>-<slug>.md и не claims/question.md")
                continue
            prefix, number, slug = m.group(1).upper(), m.group(2), m.group(3)
            letter = re.match(r"^([A-Za-z]+)", prefix).group(1).upper()
            cls = CLAIM_LETTERS.get(letter)
            if cls is None:
                naming.append(f"{rel}: буква класса {letter!r} неизвестна (C, I, S)")
                continue
            if not SLUG_RE.match(slug):
                naming.append(f"{rel}: slug {slug!r} не короткая латиница с дефисами")
            units.append(_unit(cls, rel, path, f"{letter}{int(number)}"))

    tasks = root / "tasks"
    if tasks.is_dir():
        for directory in sorted(tasks.iterdir(), key=lambda p: p.name):
            if not directory.is_dir():
                continue
            m = TASK_DIR_RE.match(directory.name)
            if not m:
                naming.append(f"tasks/{directory.name}: каталог не вида A<номер>")
                continue
            path = directory / "request.md"
            rel = path.relative_to(root).as_posix()
            if not path.is_file():
                naming.append(f"{rel}: нет request.md")
                continue
            units.append(_unit("task", rel, path, f"A{int(m.group(1))}"))

    experiments = root / "experiments"
    if experiments.is_dir():
        for directory in sorted(experiments.iterdir(), key=lambda p: p.name):
            if not directory.is_dir():
                continue
            m = EXPERIMENT_DIR_RE.match(directory.name)
            if not m:
                naming.append(f"experiments/{directory.name}: каталог не вида E<номер>")
                continue
            path = directory / "README.md"
            rel = path.relative_to(root).as_posix()
            if not path.is_file():
                naming.append(f"{rel}: нет README.md")
                continue
            units.append(_unit("experiment", rel, path, f"E{int(m.group(1))}"))

    for unit in units:
        if unit.header_errors:
            unit.header_errors = [f"{unit.rel}: {e}" for e in unit.header_errors]
        if unit.read_error:
            unit.header_errors = [f"{unit.rel}: {unit.read_error}"]
    return units, naming


def id_sort_key(unit_id: str):
    """Ключ числовой сортировки: C2 < C10, идентификаторы без номера — после."""
    m = re.match(r"^([A-Za-z]+)0*(\d+)$", unit_id or "")
    if m:
        return (0, m.group(1).upper(), int(m.group(2)), unit_id)
    return (1, unit_id or "", 0, unit_id or "")


